#!/usr/bin/env bash
# Generate every secret for the ops stack. Writes .env (chmod 600) and ops/secrets/* (chmod 600).
# Nothing here is committed (.gitignore). Run again with --force to rotate everything; see
# docs/ops/runbook.md "Rotasi secret" for the safe order.
set -euo pipefail
cd "$(dirname "$0")/.."

FORCE=0
[[ "${1:-}" == "--force" ]] && FORCE=1
ENV_FILE=".env"
SECRETS_DIR="ops/secrets"

if [[ -f "$ENV_FILE" && $FORCE -eq 0 ]]; then
  echo "$ENV_FILE sudah ada. Pakai --force untuk membuat ulang semua secret." >&2
  exit 1
fi

rand() { python3 -c "import secrets,sys; print(secrets.token_urlsafe(int(sys.argv[1])))" "$1"; }
hex() { python3 -c "import secrets,sys; print(secrets.token_hex(int(sys.argv[1])))" "$1"; }

umask 077
mkdir -p "$SECRETS_DIR"

METRICS_TOKEN="$(rand 32)"
USER_PASSWORD="$(rand 15)"
GRAFANA_PASSWORD="$(rand 18)"
LANGFUSE_ADMIN_PASSWORD="$(rand 18)"

printf '%s' "$METRICS_TOKEN" > "$SECRETS_DIR/metrics_token"
printf '%s' "$GRAFANA_PASSWORD" > "$SECRETS_DIR/grafana_admin_password"

# Local accounts (argon2 hashes) for the RBAC roles. Replace with Entra ID (AUTH_MODE=oidc) on a real deployment.
if command -v uv >/dev/null 2>&1; then PY=(uv run --quiet python); else PY=(python3); fi
DK_PW="$USER_PASSWORD" "${PY[@]}" - "$SECRETS_DIR/users.json" <<'PYEOF'
import json, os, sys
sys.path.insert(0, "src")
from dk_sales.web.auth import hash_password
h = hash_password(os.environ["DK_PW"])
users = [
    {"username": "admin", "display_name": "Admin", "roles": ["admin"]},
    {"username": "hos", "display_name": "Head of Sales", "roles": ["head_of_sales"]},
    {"username": "jabar", "display_name": "Head of Region Jawa Barat", "roles": ["head_of_region"], "regions": ["Jawa Barat"]},
    {"username": "sukro", "display_name": "Brand Manager Sukro", "roles": ["brand_manager"], "brands": ["Sukro"]},
]
for u in users:
    u["password_hash"] = h
open(sys.argv[1], "w").write(json.dumps({"users": users}, indent=2))
PYEOF

cat > "$ENV_FILE" <<EOF
# Generated by scripts/gen-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not commit.
APP_DEV_SCALE=0
AUTH_MODE=local
SECRET_KEY=$(rand 48)
ALLOWED_HOSTS=localhost,app-prod,127.0.0.1
FORCE_HTTPS=true
METRICS_TOKEN=$METRICS_TOKEN
SESSION_TTL_MINUTES=60
LOG_LEVEL=INFO
LOG_QUESTION_TEXT=false
LANGFUSE_SAMPLE_RATE=1.0
LANGFUSE_PUBLIC_KEY=pk-lf-$(hex 16)
LANGFUSE_SECRET_KEY=sk-lf-$(hex 16)
LANGFUSE_SALT=$(rand 32)
LANGFUSE_ENCRYPTION_KEY=$(hex 32)
LANGFUSE_NEXTAUTH_SECRET=$(rand 32)
LANGFUSE_POSTGRES_PASSWORD=$(hex 16)
LANGFUSE_CLICKHOUSE_PASSWORD=$(hex 16)
LANGFUSE_REDIS_PASSWORD=$(hex 16)
LANGFUSE_MINIO_PASSWORD=$(hex 16)
LANGFUSE_ADMIN_EMAIL=admin@duakelinci.local
LANGFUSE_ADMIN_PASSWORD=$LANGFUSE_ADMIN_PASSWORD
# Optional, leave empty to keep them off:
ANTHROPIC_API_KEY=
TELEGRAM_BOT_TOKEN=
TELEGRAM_CHAT_ID=
EOF
chmod 600 "$ENV_FILE"
# Compose mounts these files into containers that run as other users, so they must be world-readable;
# the directory itself is closed to other users on the host.
chmod 700 "$SECRETS_DIR"
chmod 644 "$SECRETS_DIR/metrics_token" "$SECRETS_DIR/grafana_admin_password" "$SECRETS_DIR/users.json"

# Shown once so the operator can store them in the password manager.
cat > "$SECRETS_DIR/initial-passwords.txt" <<EOF
App (https://localhost:8443): admin, hos, jabar, sukro / $USER_PASSWORD
Grafana (http://localhost:3000): admin / $GRAFANA_PASSWORD
Langfuse (http://localhost:3001): admin@duakelinci.local / $LANGFUSE_ADMIN_PASSWORD
EOF
chmod 600 "$SECRETS_DIR/initial-passwords.txt"
echo "Secret dibuat: $ENV_FILE dan $SECRETS_DIR/ (chmod 600)."
echo "Password awal ada di $SECRETS_DIR/initial-passwords.txt. Simpan di password manager lalu hapus file itu."
